#!/usr/bin/env bash
# ==========================================================================
# Dockero Compiler/Bundler
# Concatenates modular source files under lib/ and bin/ into a single
# standalone executable inside dist/dockero.
# ==========================================================================

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST_DIR="${ROOT}/dist"
OUTPUT_FILE="${DIST_DIR}/dockero"

mkdir -p "$DIST_DIR"

# Order of files to build the output:
# 1. Shebang
# 2. Config & Utilities (lib/utils/*.sh)
# 3. Parameter indexing (lib/parameter-indexing.sh)
# 4. Command scripts (lib/commands/*.sh)
# 5. Main entrypoint logic (bin/dockero)

{
    echo "#!/usr/bin/env bash"
    echo "# =========================================================================="
    echo "# Dockero CLI - Combined Standalone Executable"
    echo "# Generated automatically by bin/build.sh. Do not edit this file directly."
    echo "# =========================================================================="
    echo ""

    # Concat utilities config and library files
    for file in "${ROOT}/lib/utils/config.sh" "${ROOT}/lib/utils/colors.sh" "${ROOT}/lib/utils/log.sh" "${ROOT}/lib/utils/inipars.sh" "${ROOT}/lib/utils/docker-helpers.sh"; do
        if [[ -f "$file" ]]; then
            echo "# --- Start of ${file##*/} ---"
            sed '/^#!/d' "$file"
            echo ""
        fi
    done

    # Concat parameter indexing
    echo "# --- Start of parameter-indexing.sh ---"
    sed '/^#!/d' "${ROOT}/lib/parameter-indexing.sh"
    echo ""

    # Concat subcommands
    for cmd_file in "${ROOT}/lib/commands"/*.sh; do
        if [[ -f "$cmd_file" ]]; then
            echo "# --- Start of subcommand: ${cmd_file##*/} ---"
            sed '/^#!/d' "$cmd_file"
            echo ""
        fi
    done

    # Concat entrypoint logic
    echo "# --- Start of Entrypoint ---"
    sed '/^#!/d' "${ROOT}/bin/dockero"
    echo ""

} > "$OUTPUT_FILE"

chmod +x "$OUTPUT_FILE"
echo "Successfully compiled Dockero into ${OUTPUT_FILE} (using Bash)"
